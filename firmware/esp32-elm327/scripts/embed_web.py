"""
Embed web/*.html into include/web_assets.h as gzip byte arrays (PROGMEM),
so the firmware needs no filesystem upload in phase 1.

Runs automatically before every PlatformIO build (extra_scripts = pre:...),
or by hand:  python scripts/embed_web.py
"""
import gzip
import os
import re

try:
    Import("env")  # noqa: F821  (PlatformIO / SCons)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB = os.path.join(ROOT, "web")
OUT = os.path.join(ROOT, "include", "web_assets.h")


def symbol(name):
    return "PAGE_" + re.sub(r"[^A-Z0-9]", "_", os.path.splitext(name)[0].upper()) + "_GZ"


def build():
    parts = [
        "// Generated by scripts/embed_web.py from web/*.html — do not edit.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#include <pgmspace.h>",
        "",
    ]
    total = 0
    for name in sorted(os.listdir(WEB)):
        if not name.endswith(".html"):
            continue
        raw = open(os.path.join(WEB, name), "rb").read()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        total += len(gz)
        sym = symbol(name)
        body = ",".join(str(b) for b in gz)
        parts.append(f"// {name}: {len(raw)} bytes -> {len(gz)} gzip")
        parts.append(f"static const uint8_t {sym}[] PROGMEM = {{{body}}};")
        parts.append(f"static const size_t {sym}_LEN = {len(gz)};")
        parts.append("")
    text = "\n".join(parts)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if old != text:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print(f"embed_web: {total} bytes gzip -> include/web_assets.h")


build()
